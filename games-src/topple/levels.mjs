// Prototype levels. pic: colour letters ('.' = blank canvas). mask: '_' gap, 'S' start, 'H' heavy, 'T' timer.

function pinwheel() {
  const pic = [], mask = [];
  for (let y = 0; y < 9; y++) {
    let p = '', m = '';
    for (let x = 0; x < 9; x++) {
      const diag = x === y || x + y === 8;
      let c = '.';
      if (!diag) {
        if (y < x && y < 8 - x) c = 'r';
        else if (x > y && x > 8 - y) c = 'y';
        else if (y > x && y > 8 - x) c = 'b';
        else c = 'g';
      }
      const gap = (x === 4 && y === 4) || ((x === 3 || x === 5) && (y === 3 || y === 5));
      p += c; m += gap ? '_' : '.';
    }
    pic.push(p); mask.push(m);
  }
  pic.push('....n....', '....n....', '....n....');
  mask.push('.........', '.........', '....S....');
  return { name: 'Pinwheel', pic, mask, k: 1 };
}

